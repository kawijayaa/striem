package database

import "testing"

// Every example in Microsoft's datetime "Supported formats" tables.
func TestDocumentedDatetimeFormats(t *testing.T) {
	for _, tc := range []struct{ input, want string }{
		{"Sat, 8 Nov 14 15:05:02 GMT", "2014-11-08T15:05:02.000000000Z"},
		{"Sat, 8 Nov 14 15:05:02", "2014-11-08T15:05:02.000000000Z"},
		{"Sat, 8 Nov 14 15:05", "2014-11-08T15:05:00.000000000Z"},
		{"Sat, 8 Nov 14 15:05 GMT", "2014-11-08T15:05:00.000000000Z"},
		{"8 Nov 14 15:05:02 GMT", "2014-11-08T15:05:02.000000000Z"},
		{"8 Nov 14 15:05:02", "2014-11-08T15:05:02.000000000Z"},
		{"8 Nov 14 15:05", "2014-11-08T15:05:00.000000000Z"},
		{"8 Nov 14 15:05 GMT", "2014-11-08T15:05:00.000000000Z"},
		{"Saturday, 08-Nov-14 15:05:02 GMT", "2014-11-08T15:05:02.000000000Z"},
		{"Saturday, 08-Nov-14 15:05:02", "2014-11-08T15:05:02.000000000Z"},
		{"Saturday, 08-Nov-14 15:05 GMT", "2014-11-08T15:05:00.000000000Z"},
		{"Saturday, 08-Nov-14 15:05", "2014-11-08T15:05:00.000000000Z"},
		{"08-Nov-14 15:05:02 GMT", "2014-11-08T15:05:02.000000000Z"},
		{"08-Nov-14 15:05:02", "2014-11-08T15:05:02.000000000Z"},
		{"08-Nov-14 15:05 GMT", "2014-11-08T15:05:00.000000000Z"},
		{"08-Nov-14 15:05", "2014-11-08T15:05:00.000000000Z"},
		{"2014-11-08 15:05:25", "2014-11-08T15:05:25.000000000Z"},
		{"2014-11-08 15:05:25 GMT", "2014-11-08T15:05:25.000000000Z"},
		{"2014-11-08 15:05", "2014-11-08T15:05:00.000000000Z"},
		{"2014-11-08 15:05 GMT", "2014-11-08T15:05:00.000000000Z"},
		{"2014-11-08T15:05:25", "2014-11-08T15:05:25.000000000Z"},
		{"2014-11-08T15:05:25 GMT", "2014-11-08T15:05:25.000000000Z"},
		{"2014-11-08T15:05", "2014-11-08T15:05:00.000000000Z"},
		{"2014-11-08T15:05 GMT", "2014-11-08T15:05:00.000000000Z"},
		{"2014-1-8 5:05", "2014-01-08T05:05:00.000000000Z"},
		// Converted in Microsoft's parse operator examples.
		{"02/17/2016 08:40:01", "2016-02-17T08:40:01.000000000Z"},
		{"2/7/2016 8:40", "2016-02-07T08:40:00.000000000Z"},
		{"02/17/2016 08:40:00\n", "2016-02-17T08:40:00.000000000Z"},
		{"12/31/9999 23:59:59.9999999", "9999-12-31T23:59:59.999999900Z"},
		{"1 Jan 70 00:00", "1970-01-01T00:00:00.000000000Z"},
		{"1 Jan 68 00:00", "2068-01-01T00:00:00.000000000Z"},
		{"1970-5-12", "1970-05-12T00:00:00.000000000Z"},
		{"2025, 6, 14", "2025-06-14T00:00:00.000000000Z"},
		{"2025,6,14,13,5,9", "2025-06-14T13:05:09.000000000Z"},
		{"12-02-2022", "2022-12-02T00:00:00.000000000Z"},
	} {
		if got := kqlToDatetime(tc.input); got != tc.want {
			t.Fatalf("%q got %v want %s", tc.input, got, tc.want)
		}
	}
	for _, input := range []string{
		"Fri, 8 Nov 14 15:05", "Sat, 8-Nov-14 15:05", "Saturday, 8 Nov 14 15:05", "8 Foo 14 15:05", "31 Nov 14 15:05",
		"2014-13-08 15:05", "2014-02-30 15:05", "2014-11-08 24:00", "02/30/2016", "13/01/2016", "2014-11-08 15:05 PST", "2014-11-08 15:05 UTC",
		"8 Nov 2014 15:05", "Saturday , 08-Nov-14 15:05", "",
	} {
		if got := kqlToDatetime(input); got != nil {
			t.Fatalf("%q accepted as %v", input, got)
		}
	}
}
